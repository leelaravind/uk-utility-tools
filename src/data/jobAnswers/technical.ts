/**
 * Technical blocks — context, approach, trade-off, outcome.
 *
 * "Technical" here does not mean "software". A laboratory method, a financial
 * model, a clinical system, a production line and a construction method are all
 * technical work, and the corpus covers them alongside code so that a scientist
 * or a site engineer gets an answer in their own vocabulary.
 *
 * The trade-off blocks are the ones that separate a strong technical answer
 * from a weak one, so they are written as genuine engineering trade-offs —
 * latency against consistency, build against buy, coverage against delivery
 * speed, a manual check against an automated one — in language a non-specialist
 * interviewer can still follow.
 *
 * No block states a figure. Where a number would strengthen an outcome, the
 * block emits a `[[prompt]]` asking the visitor for their own real one.
 *
 * Adding more: append to the relevant export, take the next free
 * `tech-ctx-` / `tech-app-` / `tech-trade-` / `tech-out-` id, list every
 * `{var}` you use in `requires`, keep to one `[[prompt]]` per block, and start
 * with a fresh word — no more than two blocks in this file should begin with
 * the same word.
 */

