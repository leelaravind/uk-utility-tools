/**
 * Industry vocabulary.
 *
 * Drives two things. `signals` are matched as lowercase substrings against a
 * pasted job advert or job title so the tool can guess which industry the
 * visitor is applying into. `outcomeWords` are shown back to the visitor as
 * examples of what a measurable result tends to look like in that industry —
 * they are prompts for the visitor's own real figure and are never asserted as
 * an achievement on anyone's behalf.
 *
 * ADDING OR EDITING AN ENTRY.
 *  - There is exactly one entry per id in the INDUSTRIES union, in the same
 *    order. Do not invent ids.
 *  - Signals must discriminate. "ledger", "reconciliation" and "fca" identify
 *    finance; "team", "customer" and "communication" appear in every advert
 *    ever written and belong nowhere except `general`.
 *  - Keep signals lowercase, and long enough not to match inside unrelated
 *    words. Matching is plain substring matching with no word boundaries.
 *  - Outcome words are nouns a hiring manager in that field would recognise on
 *    sight. If it needs explaining, it is the wrong word.
 *  - British English and no real organisation names.
 */

