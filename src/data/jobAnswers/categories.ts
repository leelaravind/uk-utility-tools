/**
 * Question taxonomy — the classifier's brain.
 *
 * Drives three things: (1) deciding which category a pasted interview question
 * belongs to, (2) which answer framework the composer assembles unless the
 * visitor overrides it, and (3) the coaching shown beside the draft.
 *
 * HOW MATCHING WORKS. The engine lowercases the raw question text first, then
 * tests every `patterns` entry against it. Patterns are therefore written as
 * plain lowercase literals with no `i` flag. Each pattern that hits adds to the
 * category's score, so a category should earn its win by having several
 * distinct, specific patterns match — never by owning one very broad pattern.
 * `keywords` add a smaller amount of confidence on top.
 *
 * ADDING OR EDITING A CATEGORY.
 *  - There is exactly one entry per id in QUESTION_CATEGORIES, in the same
 *    order. Never add an id that is not in that union, and never reorder.
 *  - Keep patterns discriminating. Where two categories could plausibly both
 *    fire (challenge / problem-solving / failure), the more specific one must
 *    require its distinguishing word — "failed", "went wrong", "mistake" for
 *    failure; "disagree", "conflict", "difficult colleague" for conflict.
 *  - `general` is the fallback and deliberately carries no patterns at all, so
 *    it can never outrank a specific category.
 *  - Invariant: if `supportsStar` is false, "star" must not appear in
 *    `allowedFrameworks` either.
 *  - Tips are coaching, not platitudes. Write the thing a nervous applicant
 *    would not already know. British English throughout.
 */

