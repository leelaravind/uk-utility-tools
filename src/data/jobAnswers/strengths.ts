/**
 * Strengths blocks — the claim / evidence / relevance spine of a direct answer.
 *
 * A strong "what are your strengths" or "why should we hire you" answer is one
 * plausible claim, one piece of real evidence, and one line saying why it
 * matters for this job. Claims here are deliberately modest and specific rather
 * than grandiose; nothing says "I am the best at". Evidence blocks never invent
 * an accomplishment: they lean on `{experience}`, `{achievement}` or `{skill}`,
 * or they emit a `[[...]]` prompt asking for the visitor's own real detail.
 *
 * Adding more: append a `ContentBlock` to `CLAIMS`, `EVIDENCE` or `RELEVANCE`,
 * take the next free id in the `claim-` / `ev-` / `rel-` sequence, list every
 * `{var}` you use in `requires`, keep to one `[[prompt]]` per block, and start
 * with a fresh word — no more than two blocks in this file should begin with
 * the same word.
 */

