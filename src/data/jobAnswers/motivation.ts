/**
 * Motivation blocks — "why this company", "why this role", and the two-way fit.
 *
 * These blocks are deliberately NOT STAR-shaped. A motivation answer fails the
 * moment it could have been written about any employer, so every block here
 * either forces a checkable, specific reason out of the visitor through a
 * `[[...]]` prompt, or interpolates something the visitor actually typed.
 * Nothing here invents a fact about an employer, and salary, benefits and
 * commute are never offered as motivators.
 *
 * Adding more: append a `ContentBlock` to the relevant export, take the next
 * free id in the `mot-co-` / `mot-role-` / `mot-fit-` sequence, list every
 * `{var}` you use in `requires`, use at most one `[[prompt]]` per block, and
 * vary the opening word — no more than two blocks in this file should begin
 * with the same word.
 */

